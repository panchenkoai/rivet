-- seeds/common/oracle.sql — SELF-CONTAINED canonical seed (DDL + data + garbage).
-- Oracle Database 23ai+ (Free: gvenzl/oracle-free:23-slim). A table-for-table port
-- of seeds/common/mysql.sql; the garbage section mirrors dev/garbage/oracle.sql.
-- Run as the schema owner: sqlplus -s rivet/rivet@//host/FREEPDB1 < seeds/common/oracle.sql
-- Idempotent (DROP … IF EXISTS … PURGE, 23ai syntax); aborts on the first error.
--
-- Deviations from seeds/common/mysql.sql — each is Oracle having no exact equivalent:
--
-- Types
--   * TINYINT → NUMBER(3), SMALLINT → NUMBER(5), INT → NUMBER(10), BIGINT → NUMBER(19).
--     MySQL's signed ranges are not enforced (only the digit count is).
--   * UNSIGNED (TINYINT/SMALLINT/INT/BIGINT) → NUMBER(p) + CHECK (0 ..= max unsigned).
--     BIGINT UNSIGNED → NUMBER(20): 18446744073709551615 is stored exactly.
--   * TINYINT(1) (c_bool) → NUMBER(1) CHECK IN (0,1); BOOLEAN (is_active, is_bounce,
--     c_boolean) → native BOOLEAN (23ai). MySQL's BOOLEAN is TINYINT(1), so Oracle
--     distinguishes the two where MySQL cannot.
--   * DECIMAL(p,s) → NUMBER(p,s). FLOAT → BINARY_FLOAT, DOUBLE → BINARY_DOUBLE.
--   * DATE → DATE. Oracle DATE always carries a time of day (here 00:00:00).
--   * TIME(6) → INTERVAL DAY(0) TO SECOND(6) (Oracle has no time-of-day type).
--   * DATETIME → TIMESTAMP(0), DATETIME(6) → TIMESTAMP(6) (both naive).
--   * TIMESTAMP(6) (MySQL: UTC-stored, rendered in the session zone) →
--     TIMESTAMP(6) WITH LOCAL TIME ZONE — same semantics. Seeded with an explicit
--     +00:00 literal, matching MySQL's `SET time_zone = '+00:00'` before the insert.
--   * DEFAULT CURRENT_TIMESTAMP on a DATETIME → DEFAULT LOCALTIMESTAMP.
--   * TEXT → VARCHAR2(4000) (all seeded values fit; MySQL TEXT's 64 KiB ceiling is
--     not reproduced). LONGTEXT/MEDIUMTEXT (content_items.body/raw_html,
--     long_text, medium_text) → CLOB, since they exceed the 4000-byte VARCHAR2
--     limit under max_string_size=STANDARD.
--   * CHAR(n) → CHAR(n). MySQL strips trailing spaces from CHAR on read
--     ('char-a    ' reads 'char-a'); Oracle returns the blank-padded value.
--   * BINARY(4) → RAW(4). MySQL right-pads BINARY with 0x00, so the stored values
--     are seeded pre-padded: UNHEX('cafe') → CAFE0000, UNHEX('00') → 00000000.
--   * VARBINARY(8) → RAW(8); BLOB → BLOB. UNHEX('') (zero-length, NOT NULL) →
--     EMPTY_BLOB(), which is zero-length and NOT NULL in Oracle too.
--   * JSON → native JSON (23ai). JSON_OBJECT/JSON_ARRAY build the same documents
--     ({"seed":true,"i":1}, ["a","b"], {} …); Oracle may serialize key order/spacing
--     differently.
--   * ENUM('a','b','c') → VARCHAR2(1) + CHECK IN. SET('x','y','z') → VARCHAR2(5)
--     + CHECK over the canonical member combinations. YEAR → NUMBER(4) + CHECK
--     (1901..2155, MySQL's YEAR range). BIT(1) → NUMBER(1) CHECK IN (0,1);
--     BIT(8) → NUMBER(3) CHECK 0..255 (numeric value, as MySQL's b'…' reads back).
--   * AUTO_INCREMENT → GENERATED BY DEFAULT ON NULL AS IDENTITY. The fill inserts
--     id = i explicitly (MySQL's CTE fill yields id = i), then the identity is moved
--     past the max with START WITH LIMIT VALUE so later inserts do not collide.
--   * ENGINE/CHARSET clauses dropped (DB charset is AL32UTF8).
--   * rivet_type_matrix.uid: UID is an Oracle RESERVED WORD (ORA-03050), so the
--     column is the quoted identifier "UID" (catalog name UID, like every other
--     column). A reader must quote it; this is the one quoted identifier here.
--
-- Values
--   * EMPTY STRING IS NULL IN ORACLE. row_hash_probe row 4 seeds a = '' in MySQL;
--     here it arrives as NULL, so rows 3 and 4 are IDENTICAL (a NULL, b 'x'). That
--     is expected Oracle semantics, not a seeding bug — the "absent vs zero-length"
--     distinction cannot be expressed in an Oracle VARCHAR2.
--   * RAND(i) has no reproducible Oracle counterpart. users.balance →
--     MOD(i*7919, 20000001)/100 (same 0..200000 range, 2 dp, deterministic);
--     orders_coalesce.updated_at is NULL when MOD(i*37, 100) < 35 (exactly 35%,
--     scattered — MySQL's RAND(i) < 0.35 gives ~35%). Which rows are NULL differs.
--   * MySQL escapes: 'line1\nline2' → 'line1' || CHR(10) || 'line2';
--     'quote \"and\", comma' → 'quote "and", comma'.
--   * Non-ASCII literal 'unicode: 日本語 🚀' is built with UNISTR so it survives any
--     sqlplus client NLS_LANG.
--   * repeat('L', n) → RPAD for n <= 4000, TO_CLOB-concatenation beyond (CLOB).
--   * ELT/IF/CONCAT/HEX/% → DECODE/CASE/||/TO_CHAR(i,'FMXXXXXXXX')/MOD.
--     DATE_SUB(d, INTERVAL -x UNIT) → d + NUMTODSINTERVAL(x, 'UNIT').
--   * ANALYZE TABLE → DBMS_STATS.GATHER_TABLE_STATS.
--   * Unquoted identifiers: Oracle stores every table/column name UPPER-case.

