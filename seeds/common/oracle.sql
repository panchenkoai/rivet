CREATE TABLE users (
    id NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    name VARCHAR2(100) NOT NULL,
    email VARCHAR2(200) NOT NULL,
    age NUMBER(10),
    balance NUMBER(12,2),
    is_active BOOLEAN DEFAULT TRUE,
    bio VARCHAR2(4000),
    created_at TIMESTAMP(0) DEFAULT LOCALTIMESTAMP NOT NULL,
    updated_at TIMESTAMP(0) DEFAULT LOCALTIMESTAMP NOT NULL
);

CREATE TABLE orders (
    id NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    user_id NUMBER(10) NOT NULL,
    product VARCHAR2(200) NOT NULL,
    quantity NUMBER(10) NOT NULL,
    price NUMBER(10,2) NOT NULL,
    status VARCHAR2(20) DEFAULT 'pending' NOT NULL,
    notes VARCHAR2(4000),
    ordered_at TIMESTAMP(0) DEFAULT LOCALTIMESTAMP NOT NULL,
    updated_at TIMESTAMP(0) DEFAULT LOCALTIMESTAMP NOT NULL,
    FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE events (
    id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    user_id NUMBER(10) NOT NULL,
    event_type VARCHAR2(50) NOT NULL,
    payload JSON,
    ip_address VARCHAR2(45),
    created_at TIMESTAMP(0) DEFAULT LOCALTIMESTAMP NOT NULL,
    FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE INDEX idx_orders_updated_at ON orders(updated_at);
CREATE INDEX idx_events_created_at ON events(created_at);
CREATE INDEX idx_events_user_id ON events(user_id);

