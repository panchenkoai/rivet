/// What the scaffold DECIDED for a table, as data rather than as YAML text.
///
/// Exists so the strategy snapshot written to the state store and the config
/// written to disk come from ONE rule. Re-deriving the decision for the snapshot
/// would be the self-oracle shape this repo has paid for: two copies of a rule
/// agree until one is edited, and then the audit trail describes a choice that
/// was never made.
///
/// `agrees_with_the_generated_yaml` keeps them honest — it parses what
/// `generate_config` actually emitted and compares, so the check's oracle is the
/// artifact rather than a second implementation.
#[derive(Debug, Clone, PartialEq)]
pub(crate) struct DecidedStrategy {
    pub mode: String,
    /// Finer than `mode:` — both keyset and range are `mode: chunked`.
    pub kind: &'static str,
    pub key_column: Option<String>,
    pub chunk_size: Option<i64>,
}

pub(crate) fn decided_strategy(
    info: &crate::init::TableInfo,
    mode_override: Option<&str>,
    keyset_form: bool,
) -> DecidedStrategy {
    let mode = mode_override
        .map(str::to_string)
        .unwrap_or_else(|| info.suggest_mode().to_string());
    let mode = if mode == "chunked" && chunk_key_missing(info, keyset_form) {
        "full".to_string()
    } else {
        mode
    };
    match mode.as_str() {
        "chunked" => {
            let size = info.suggest_chunk_size() as i64;
            if let Some(pk) = info.keysettable_pk_column().filter(|_| keyset_form) {
                DecidedStrategy {
                    mode,
                    kind: "keyset",
                    key_column: Some(pk.to_string()),
                    chunk_size: Some(size),
                }
            } else {
                DecidedStrategy {
                    mode,
                    kind: "range",
                    key_column: info.best_chunk_column().map(str::to_string),
                    chunk_size: Some(size),
                }
            }
        }
        "incremental" => DecidedStrategy {
            kind: "incremental",
            key_column: info.chosen_cursor_column(),
            chunk_size: None,
            mode,
        },
        _ => DecidedStrategy {
            kind: "full",
            key_column: None,
            chunk_size: None,
            mode,
        },
    }
}

#[cfg(test)]
mod load_block_tests {
    use super::*;

    /// The `load:` block appears only when a warehouse was NAMED, and it carries
    /// the values an operator is expected to review rather than a silent default.
    #[test]
    fn the_load_block_is_written_only_when_a_warehouse_is_named() {
        let bare = InitYamlDestination {
            gcs_bucket: Some("b".into()),
            gcs_credentials_file: None,
            s3_bucket: None,
            s3_region: None,
            bigquery_project: None,
            bigquery_dataset: None,
        };
        assert!(
            load_block_lines(&bare, true).is_empty(),
            "no warehouse named, no load block"
        );

        let named = InitYamlDestination {
            bigquery_project: Some("p".into()),
            bigquery_dataset: Some("d".into()),
            ..bare
        };
        let block = load_block_lines(&named, true).join("\n");
        for want in [
            "load:",
            "  target: bigquery",
            "  project: p",
            "  dataset: d",
            "  pk: auto",
            "  layout: base_buffer",
        ] {
            assert!(block.contains(want), "missing `{want}` in:\n{block}");
        }
        assert!(
            block.contains("Review every value"),
            "the block says it is a guess: {block}"
        );

        // A scaffold whose exports OVERWRITE their tables must not promise a
        // layout `rivet compact` openly skips — it names the way to get one.
        let overwriting = load_block_lines(&named, false).join("\n");
        assert!(
            !overwriting.contains("layout:"),
            "no delta, no layout key: {overwriting}"
        );
        assert!(
            overwriting.contains("--mode incremental"),
            "it names the way to the compaction cycle: {overwriting}"
        );
    }
}
